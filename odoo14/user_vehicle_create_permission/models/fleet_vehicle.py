# -*- coding: utf-8 -*-
"""บังคับสิทธิ์การสร้างยานพาหนะ

บังคับที่ ``create`` ไม่ใช่แค่ซ่อนปุ่มบนหน้าจอ เพราะการซ่อนปุ่มกันได้แค่
การกดผิดเท่านั้น ไม่ได้กันการสร้างผ่านนำเข้าไฟล์ ผ่านหน้าจออื่นที่มีปุ่ม
สร้างในตัว หรือผ่าน API

ห้ามเฉพาะการ "สร้างใหม่" เท่านั้น การดูและการแก้ไขคันที่มีอยู่
ยังเป็นไปตามสิทธิ์เดิมของผู้ใช้ ไม่ได้ถูกโมดูลนี้แตะต้อง
"""
from odoo import _, api, models
from odoo.exceptions import UserError


class FleetVehicle(models.Model):
    _inherit = 'fleet.vehicle'

    def _check_can_create_vehicle(self):
        """ผู้ใช้ปัจจุบันสร้างยานพาหนะได้ไหม

        ยกเว้นให้เฉพาะ superuser (``sudo``) ซึ่งคือตอนติดตั้งโมดูล นำเข้า
        ข้อมูลตั้งต้น หรือระบบอื่นสร้างให้เบื้องหลัง — ไม่ใช่คนกดสร้างเอง

        ไม่ยกเว้นให้ผู้ดูแลระบบ เพราะผู้ใช้เกือบทุกคนที่ต้องคุมอยู่ในกลุ่ม
        ผู้ดูแลระบบ ถ้ายกเว้นให้ ช่องติ๊กจะไม่มีผลกับใครเลย
        ผู้ดูแลระบบที่ต้องสร้างจริงก็ไปติ๊กให้ตัวเองได้อยู่แล้ว
        """
        if self.env.su:
            return
        if self.env.user.can_create_vehicle:
            return
        raise UserError(_(
            'ไม่สามารถสร้างยานพาหนะใหม่ได้\n\n'
            'ผู้ใช้ "%(user)s" ยังไม่ได้รับสิทธิ์สร้างยานพาหนะ\n\n'
            'กรุณาติดต่อผู้ดูแลระบบให้ติ๊ก "สามารถสร้างยานพาหนะได้"\n'
            'ที่ ตั้งค่า > ผู้ใช้ > %(user)s > แท็บการตั้งค่าส่วนตัว\n\n'
            'หมายเหตุ: คุณยังดูและแก้ไขยานพาหนะที่มีอยู่ได้ตามปกติ'
        ) % {'user': self.env.user.name})

    @api.model_create_multi
    def create(self, vals_list):
        self._check_can_create_vehicle()
        return super().create(vals_list)
