from odoo import fields, models


class UtmCampaign(models.Model):
    _inherit = 'utm.campaign'

    npd_free_shipping = fields.Boolean(
        string='เป็นโปรส่งฟรี',
        help='ติ๊กแล้วใบสั่งขายที่เลือกแคมเปญนี้จะได้ค่าขนส่งเป็น 0 '
             'เมื่อระยะทางไม่เกินที่กำหนดด้านล่าง',
    )
    npd_free_shipping_max_km = fields.Float(
        string='ส่งฟรีเมื่อระยะทางไม่เกิน (กม.)',
        digits=(16, 2),
        help='ระยะทางเท่ากับตัวเลขนี้ถือว่ายังอยู่ในโปร เกินกว่านี้คิดค่าขนส่งตามปกติ\n'
             'ปล่อยเป็น 0 = ยังไม่ได้กำหนดเงื่อนไข ระบบจะคิดค่าขนส่งตามปกติทุกใบ',
    )
