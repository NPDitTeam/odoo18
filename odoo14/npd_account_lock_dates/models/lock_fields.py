def thai_today(env):
    """วันนี้ตามเวลาไทย

    ผู้ใช้ที่ไม่ได้ตั้งเขตเวลา context_today จะใช้ UTC ทำให้วันที่ 1 ก่อน 07:00 น.
    ยังเป็นเดือนก่อน แล้วปุ่ม "ล็อกถึงสิ้นเดือนที่แล้ว" จะถอยไปผิดเดือน จึงใช้กรุงเทพเป็นค่าสำรอง
    """
    tz = env.context.get('tz') or env.user.tz or 'Asia/Bangkok'
    return fields.Date.context_today(env['res.company'].with_context(tz=tz))


def max_lock_date(env):
    """วันสุดท้ายของเดือนที่แล้ว = วันล็อกสูงสุดที่ยอมให้ตั้ง

    งวดที่ยังไม่จบห้ามล็อก เพราะเอกสารใหม่ที่ลงวันที่ในช่วงล็อกจะถูกย้ายวันที่ไปงวดถัดไปเงียบ ๆ
    เกณฑ์เดียวกับตัวช่วยปิดงบของ AI-IT (_lock_allowed)
    """
    return thai_today(env).replace(day=1) - timedelta(days=1)


def is_unlock(old, new):
    """ปลดล็อก = เดิมล็อกอยู่ แล้วล้างทิ้งหรือถอยวันลง"""
    return bool(old) and (not new or new < old)


def lock_direction(old, new):
    # ล้างค่าล็อกทิ้งก็นับเป็นการปลดล็อก
    return 'lock' if new and (not old or new > old) else 'unlock'


def may_unlock(env):
    """ผู้ที่ปลดล็อก/ถอยวันล็อกได้: กลุ่มผู้ปิดงวดบัญชี หรือ OdooBot (สคริปต์ shell / cron / ติดตั้งโมดูล)

    ไม่ดู env.su เพราะ AI-IT และโค้ดอื่นเขียนบริษัทผ่าน sudo อยู่แล้ว
    ภายใต้ sudo env.user ยังเป็นผู้ใช้จริงที่กด จึงใช้แยกสิทธิ์ได้
    """
    return env.uid == SUPERUSER_ID or env.user.has_group(LOCK_GROUP)
